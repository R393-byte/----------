#Написати програму, яка приймає на вхід рядок, введений з клавіатури, і підраховує кількість входження в рядок першої літери, з якої починається цей рядок.


text = input("Введіть рядок: ")

if text:
    first_string = text[0]
    count = text.count(first_string)
    print(f"Перший символ '{first_string}' зустрічається {count} раз(ів).")
else:
    print("Ви ввели порожній рядок.")















